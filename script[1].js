const SUPABASE_URL = "PASTE_YOUR_SUPABASE_PROJECT_URL_HERE";
const SUPABASE_ANON_KEY = "PASTE_YOUR_SUPABASE_ANON_PUBLIC_KEY_HERE";
const TABLE = "visitors";

const $ = id => document.getElementById(id);
const state = { staff: sessionStorage.getItem("medivisit_staff") || "", db: null };
const routeNames = {
  dashboard: { title: "Overview", eyebrow: "VISITOR OPERATIONS / DASHBOARD" },
  checkin: { title: "New check-in", eyebrow: "VISITOR OPERATIONS / REGISTRATION" },
  visitors: { title: "Visitor records", eyebrow: "VISITOR OPERATIONS / DATABASE" }
};

function escapeHTML(value) {
  return String(value ?? "").replace(/[&<>"']/g, char => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
  }[char]));
}
function showToast(message) {
  const toast = $("toast");
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(showToast.timer);
  showToast.timer = setTimeout(() => toast.classList.remove("show"), 2600);
}
function isConfigured() {
  return !SUPABASE_URL.includes("PASTE_") && !SUPABASE_ANON_KEY.includes("PASTE_");
}
function initDatabase() {
  if (!isConfigured()) {
    $("connectionLabel").textContent = "Database setup required";
    return false;
  }
  if (!window.supabase) {
    $("connectionLabel").textContent = "Database library unavailable";
    return false;
  }
  const client = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
  state.db = client;
  $("connectionLabel").textContent = "Cloud database";
  return true;
}
function setStaff(name) {
  state.staff = name;
  sessionStorage.setItem("medivisit_staff", name);
  $("staffNameSide").textContent = name;
  $("staffAvatar").textContent = name.charAt(0).toUpperCase();
  $("staffAvatarTop").textContent = name.charAt(0).toUpperCase();
}
function showApplication() {
  $("loginPage").classList.add("hidden");
  $("appShell").classList.remove("hidden");
  $("staffNameSide").textContent = state.staff;
  $("staffAvatar").textContent = state.staff.charAt(0).toUpperCase();
  $("staffAvatarTop").textContent = state.staff.charAt(0).toUpperCase();
}
function navigate() {
  if (!state.staff) {
    $("loginPage").classList.remove("hidden");
    $("appShell").classList.add("hidden");
    return;
  }
  showApplication();
  const requested = location.hash.replace("#", "") || "dashboard";
  const page = routeNames[requested] ? requested : "dashboard";
  Object.keys(routeNames).forEach(name => {
    $(`${name}View`).classList.toggle("hidden", name !== page);
    document.querySelector(`[data-route="${name}"]`).classList.toggle("active", name === page);
  });
  $("pageTitle").textContent = routeNames[page].title;
  $("pageEyebrow").textContent = routeNames[page].eyebrow;
  if (page === "dashboard") loadDashboard();
  if (page === "visitors") loadVisitors();
  if (page === "checkin") {
    $("visit_date").value = new Date().toLocaleDateString("en-CA");
    $("visitor_name").focus();
  }
  window.scrollTo({ top: 0, behavior: "smooth" });
}
async function requireDatabase() {
  if (state.db) return true;
  showToast("Set your Supabase URL and anon key in script.js first.");
  return false;
}
async function fetchVisitors(search = "", status = "All") {
  if (!await requireDatabase()) throw new Error("Connect Supabase to load visitor records.");
  let query = state.db.from(TABLE).select("*").order("id", { ascending: false });
  if (search) {
    const safe = search.replace(/[,%()]/g, " ");
    query = query.or(`visitor_name.ilike.%${safe}%,patient_name.ilike.%${safe}%,phone.ilike.%${safe}%,department.ilike.%${safe}%`);
  }
  if (status !== "All") query = query.eq("status", status);
  const { data, error } = await query;
  if (error) throw error;
  return data || [];
}
function badge(status) {
  return `<span class="badge ${status === "Inside" ? "inside" : "done"}">${escapeHTML(status)}</span>`;
}
async function loadDashboard() {
  if (!state.db) {
    $("recentRows").innerHTML = '<tr><td colspan="5" class="empty-cell">Add your Supabase credentials in script.js to connect the cloud database.</td></tr>';
    ["totalStat", "todayStat", "insideStat", "completedStat"].forEach(id => $(id).textContent = "—");
    return;
  }
  try {
    const visitors = await fetchVisitors();
    const today = new Date().toLocaleDateString("en-CA");
    const stats = {
      total: visitors.length,
      today: visitors.filter(v => v.visit_date === today).length,
      inside: visitors.filter(v => v.status === "Inside").length,
      completed: visitors.filter(v => v.status === "Checked out").length
    };
    $("totalStat").textContent = stats.total;
    $("todayStat").textContent = stats.today;
    $("insideStat").textContent = stats.inside;
    $("completedStat").textContent = stats.completed;
    $("recentRows").innerHTML = visitors.length ? visitors.slice(0, 6).map(v => `
      <tr><td><strong>${escapeHTML(v.visitor_name)}</strong><span class="sub-cell">${escapeHTML(v.phone)}</span></td>
      <td>${escapeHTML(v.patient_name)}</td><td>${escapeHTML(v.department)}</td>
      <td>${escapeHTML(v.check_in)}</td><td>${badge(v.status)}</td></tr>`).join("")
      : '<tr><td colspan="5" class="empty-cell">No visitors yet. Register your first visitor to get started.</td></tr>';
  } catch (error) {
    $("recentRows").innerHTML = `<tr><td colspan="5" class="empty-cell">${escapeHTML(error.message)}</td></tr>`;
  }
}
$("loginForm").addEventListener("submit", event => {
  event.preventDefault();
  const name = $("staffName").value.trim();
  if (!name) return;
  setStaff(name);
  location.hash = "dashboard";
  navigate();
});
$("logoutButton").addEventListener("click", () => {
  sessionStorage.removeItem("medivisit_staff");
  state.staff = "";
  location.hash = "";
  $("staffName").value = "";
  $("appShell").classList.add("hidden");
  $("loginPage").classList.remove("hidden");
});
window.addEventListener("hashchange", navigate);

$("visitorForm").addEventListener("submit", async event => {
  event.preventDefault();
  if (!await requireDatabase()) return;
  const button = $("saveVisitorButton");
  button.disabled = true;
  button.textContent = "Saving…";
  const values = Object.fromEntries(new FormData(event.currentTarget).entries());
  const checkIn = new Date().toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });
  try {
    const { data, error } = await state.db.from(TABLE).insert([{
      ...values,
      phone: values.phone.trim(),
      visitor_name: values.visitor_name.trim(),
      patient_name: values.patient_name.trim(),
      purpose: values.purpose.trim(),
      check_in: checkIn,
      status: "Inside"
    }]).select().single();
    if (error) throw error;
    $("formMessage").textContent = `✓ ${data.visitor_name} has been checked in successfully.`;
    $("formMessage").className = "form-message success";
    event.currentTarget.reset();
    showToast("Visitor saved to cloud database.");
    setTimeout(() => { location.hash = "visitors"; }, 650);
  } catch (error) {
    $("formMessage").textContent = error.message || "Could not save visitor.";
    $("formMessage").className = "form-message error";
  } finally {
    button.disabled = false;
    button.innerHTML = 'Save visitor record <span>→</span>';
  }
});
async function loadVisitors() {
  if (!state.db) {
    $("visitorRows").innerHTML = '<tr><td colspan="6" class="empty-cell">Connect Supabase to load visitor history.</td></tr>';
    $("recordCount").textContent = "0 RECORDS";
    return;
  }
  try {
    const visitors = await fetchVisitors($("searchInput").value.trim(), $("statusFilter").value);
    $("recordCount").textContent = `${visitors.length} RECORD${visitors.length === 1 ? "" : "S"}`;
    $("visitorRows").innerHTML = visitors.length ? visitors.map(v => `
      <tr><td><strong>${escapeHTML(v.visitor_name)}</strong><span class="sub-cell">${escapeHTML(v.phone)}</span></td>
      <td>${escapeHTML(v.patient_name)}</td><td>${escapeHTML(v.department)}</td>
      <td>${escapeHTML(v.visit_date)}<span class="sub-cell">${escapeHTML(v.check_in)}${v.check_out ? " – " + escapeHTML(v.check_out) : ""}</span></td>
      <td>${badge(v.status)}</td>
      <td>${v.status === "Inside" ? `<button class="table-action" data-checkout="${v.id}">Check out</button>` : '<span class="muted">Completed</span>'}</td></tr>`).join("")
      : '<tr><td colspan="6" class="empty-cell">No matching visitor records found.</td></tr>';
  } catch (error) {
    $("visitorRows").innerHTML = `<tr><td colspan="6" class="empty-cell">${escapeHTML(error.message)}</td></tr>`;
  }
}
$("searchInput").addEventListener("input", loadVisitors);
$("statusFilter").addEventListener("change", loadVisitors);
$("visitorRows").addEventListener("click", async event => {
  const button = event.target.closest("[data-checkout]");
  if (!button || !state.db) return;
  if (!confirm("Mark this visitor as checked out?")) return;
  button.disabled = true;
  const checkOut = new Date().toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });
  try {
    const { error } = await state.db.from(TABLE).update({
      status: "Checked out",
      check_out: checkOut
    }).eq("id", button.dataset.checkout);
    if (error) throw error;
    showToast("Visitor checked out.");
    loadVisitors();
  } catch (error) {
    alert(error.message || "Could not check out visitor.");
    button.disabled = false;
  }
});

initDatabase();
if (state.staff) navigate();
else navigate();
